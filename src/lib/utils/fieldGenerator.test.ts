import { describe, it, expect } from 'vitest';
import { generateValue, isAutoGeneratedField, isStandaloneRule, generateAutoFields } from './fieldGenerator';

describe('generateValue', () => {
  const allFields = {
    'Passenger_Name': 'John Doe',
    'Flight_Number': 'TK123',
    'Departure_City': 'Istanbul',
  };

  it('should handle simple static text', () => {
    expect(generateValue('Hello_World')).toBe('Hello World');
  });

  it('should handle dependency references', () => {
    expect(generateValue('(dep_Passenger_Name)', allFields)).toBe('John Doe');
  });

  it('should handle mixed static and dependency', () => {
    expect(generateValue('Name:_ (dep_Passenger_Name)', allFields)).toBe('Name:  John Doe');
  });

  it('should handle multiple dependencies', () => {
    expect(generateValue('(dep_Flight_Number):_ (dep_Departure_City)', allFields)).toBe('TK123:  Istanbul');
  });

  it('should handle underscores inside dependencies correctly', () => {
    // The DSL uses underscores for spaces, but they should be preserved inside (dep_...)
    expect(generateValue('Info:_ (dep_Passenger_Name)', allFields)).toBe('Info:  John Doe');
  });

  it('should handle newlines', () => {
    expect(generateValue('Line1\\nLine2')).toBe('Line1\nLine2');
  });

  it('should handle random numbers', () => {
    const val = generateValue('(rn[6])');
    expect(val).toMatch(/^\d{6}$/);
  });
});

describe('parseQRCodePattern (Regex Test)', () => {
  const decode = (pattern: string) => {
    return pattern.replace(/(\([^)]+\))|(_)/g, (_match, group1, _group2) => {
      if (group1) return group1;
      return ' ';
    });
  };

  it('should decode underscores outside parentheses', () => {
    expect(decode('Name:_John')).toBe('Name: John');
  });

  it('should NOT decode underscores inside parentheses', () => {
    expect(decode('(dep_Passenger_Name)')).toBe('(dep_Passenger_Name)');
  });

  it('should handle mixed content', () => {
    expect(decode('Name:_(dep_Passenger_Name)')).toBe('Name: (dep_Passenger_Name)');
  });
});

describe('isAutoGeneratedField (duplicate document)', () => {
  const base = { name: 'x', type: 'text' };
  it('copies user-filled fields, including dates and manual gen values', () => {
    expect(isAutoGeneratedField({ ...base, id: 'Date_of_Birth', type: 'date', dateFormat: 'DD/MM/YYYY' })).toBe(false);
    expect(isAutoGeneratedField({ ...base, id: 'Full_Name' })).toBe(false);
    expect(isAutoGeneratedField({ ...base, id: 'Photo', type: 'upload' })).toBe(false);
    expect(isAutoGeneratedField({ ...base, id: 'Ref', type: 'gen', generationRule: '(rn[6])' })).toBe(false);
  });

  it('regenerates tracking IDs and AUTO / QR / barcode fields', () => {
    expect(isAutoGeneratedField({ ...base, id: 'Tracking_ID' })).toBe(true);
    expect(isAutoGeneratedField({ ...base, id: 'Track', isTrackingId: true })).toBe(true);
    expect(isAutoGeneratedField({ ...base, id: 'Ref', type: 'gen', generationRule: 'AUTO:(rn[6])' })).toBe(true);
    expect(isAutoGeneratedField({ ...base, id: 'QR', type: 'qrcode', generationRule: '(Full_Name)' })).toBe(true);
  });
});

describe('isStandaloneRule (keep the shown value on Create)', () => {
  it('accepts purely random / date / env rules', () => {
    expect(isStandaloneRule('AUTO:(ru[2])(rn[6])')).toBe(true);
    expect(isStandaloneRule('AUTO:TX-(rn[8])')).toBe(true);
    expect(isStandaloneRule('(date[YYYY-MM-DD])(rc[4])')).toBe(true);
  });
  it('rejects rules that read other fields', () => {
    expect(isStandaloneRule('AUTO:(dep_Name[w1])(rn[4])')).toBe(false);
    expect(isStandaloneRule('(Full_Name[ch1-3])')).toBe(false);
    expect(isStandaloneRule('(A[10])')).toBe(false);
    expect(isStandaloneRule(undefined)).toBe(false);
    expect(isStandaloneRule('AUTO:')).toBe(false);
  });
});

describe('generateAutoFields keeps an already generated standalone value', () => {
  const tracking = { id: 'Tracking_ID', name: 'Tracking', type: 'gen', isTrackingId: true, generationRule: 'AUTO:(rn[8])', defaultValue: '00000000' };
  it('fills the template sample once, then keeps it across re-renders', () => {
    const first = generateAutoFields([{ ...tracking, currentValue: '00000000' }]);
    const id = first[0].currentValue;
    expect(id).toMatch(/^\d{8}$/);
    expect(id).not.toBe('00000000');
    expect(generateAutoFields(first)[0].currentValue).toBe(id);
    expect(generateAutoFields(generateAutoFields(first))[0].currentValue).toBe(id);
  });
  it('still rebuilds values that depend on other fields', () => {
    const fields = [
      { id: 'Name', name: 'Name', type: 'text', currentValue: 'Ada Okafor' },
      { id: 'QR', name: 'QR', type: 'qrcode', generationRule: '(dep_Name[w1])', currentValue: 'Old' },
    ];
    expect(generateAutoFields(fields)[1].currentValue).toBe('Ada');
  });
});
